import type { AppLocale } from '@/lib/locale'

type RuntimePattern = {
	test: RegExp
	replace: (match: RegExpMatchArray) => string
}

type RuntimeExactMap = Record<Exclude<AppLocale, 'en'>, Record<string, string>>

const monthLookup: Record<string, number> = {
	Jan: 0,
	Feb: 1,
	Mar: 2,
	Apr: 3,
	May: 4,
	Jun: 5,
	Jul: 6,
	Aug: 7,
	Sep: 8,
	Oct: 9,
	Nov: 10,
	Dec: 11,
}

function formatLocalizedDate(locale: Exclude<AppLocale, 'en'>, input: string) {
	const match = input.match(/^(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\s+(\d{1,2}),\s+(\d{4})$/)
	if (!match) return input

	const monthIndex = monthLookup[match[1]]
	if (monthIndex === undefined) return input

	const day = Number(match[2])
	const year = Number(match[3])
	const date = new Date(Date.UTC(year, monthIndex, day))

	return new Intl.DateTimeFormat(locale, {
		month: 'short',
		day: 'numeric',
		year: 'numeric',
	}).format(date)
}

